from orpheus.calc import evaluate, number
from orpheus.numbers import cardinal, ordinal, speakable, to_digits


def test_numbers_agree_with_the_words_around_them():
    cases = {
        "Сейчас 17:24.": "Сейчас семнадцать двадцать четыре.",
        "Сейчас 17:00.": "Сейчас семнадцать часов.",
        "с 12:00 до 13:30 Физика": "с двенадцати часов до тринадцати тридцати Физика",
        "в 10:05": "в десять ноль пять",
        "к 21:00": "к двадцати одному часу",
        "в 1:00": "в один час",
        "в 00:00": "в полночь",
        "Сегодня суббота, 26 сентября.": "Сегодня суббота, двадцать шестое сентября.",
        "до 1 октября осталось 5 дней": "до первого октября осталось пять дней",
        "на 3 октября": "на третье октября",
        "с 2 мая": "со второго мая",
        "Сейчас 2026 год.": "Сейчас две тысячи двадцать шестой год.",
        "в 2026 году": "в две тысячи двадцать шестом году",
        "26.09.2026": "двадцать шестое сентября две тысячи двадцать шестого года",
        "осталась 1 минута": "осталась одна минута",
        "21 задача, 2 заметки, 1 событие": "двадцать одна задача, две заметки, одно событие",
        "20% от 3 000 — 600": "двадцать процентов от трёх тысяч — шестьсот",
        "Будет 3,33.": "Будет три целых тридцать три сотых.",
        "1,5 литра": "одна целая пять десятых литра",
        "код от домофона 4521": "код от домофона четыре пять два один",
        "с 2-го числа": "со второго числа",
        "1 000 000": "миллион",
        "без цифр": "без цифр",
    }
    for text, spoken in cases.items():
        assert speakable(text) == spoken, text


def test_the_planner_answers_sound_right():
    assert speakable("Добавил на завтра, воскресенье, 27 сентября: в 12:00 Созвон с Петей.") == \
        "Добавил на завтра, воскресенье, двадцать седьмое сентября: в двенадцать часов Созвон с Петей."
    assert speakable("До Нового года 97 дней.") == "До Нового года девяносто семь дней."


def test_cardinals_and_ordinals():
    assert cardinal(0) == "ноль"
    assert cardinal(1990) == "тысяча девятьсот девяносто"
    assert cardinal(2, gender="f") == "две"
    assert cardinal(21, "gen", "f") == "двадцати одной"
    assert cardinal(345, "dat") == "трёмстам сорока пяти"
    assert cardinal(1_234_567) == "миллион двести тридцать четыре тысячи пятьсот шестьдесят семь"
    assert ordinal(2026, "gen") == "две тысячи двадцать шестого"
    assert ordinal(3, "n") == "третье"
    assert ordinal(40, "gen") == "сорокового"
    assert ordinal(2000) == "двухтысячный"
    assert ordinal(110) == "сто десятый"


def test_number_words_become_digits():
    cases = {
        "через два часа выпить": "через 2 часа выпить",
        "двадцать пятого сентября": "25 сентября",
        "сто двадцать пять": "125",
        "три тысячи двести": "3200",
        "в восемь вечера": "в 8 вечера",
        "первое октября": "1 октября",
        "двадцать первого": "21",
        "(два), три.": "(2), 3.",
        "нет чисел": "нет чисел",
    }
    for text, digits in cases.items():
        assert to_digits(text) == digits, text


def test_sums_said_aloud():
    cases = {
        "15 умножить на 37": 555, "20% от 3 000": 600, "2 плюс 2 умножить на 2": 6, "корень из 144": 12,
        "2 в степени 10": 1024, "5 в квадрате": 25, "300 плюс 15%": 345, "15 на 37": 555,
        "двадцать пять плюс семнадцать": 42, "12,5 * 4": 50, "7 x 8": 56, "10 минус 15": -5, "минус 5 плюс 3": -2,
        "3,5 разделить на 2": 1.75,
    }
    for text, value in cases.items():
        found = evaluate(text)
        assert found is not None and abs(found[0] - value) < 1e-9, text
    for text in ["стоить ремонт", "5", "полтора землекопа", "", "плюс"]:
        assert evaluate(text) is None, text
    assert evaluate("100 разделить на 3")[1] == "100 разделить на 3"
    assert number(100 / 3) == "33,33" and number(1234567) == "1 234 567" and number(-0.5) == "-0,5"
